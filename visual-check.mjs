import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') console.log('CONSOLE:', message.text()); });
await page.goto('http://localhost:5173', { waitUntil: 'networkidle' });
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: 'artifacts/desktop-hub.png', fullPage: true });
console.log('Desktop layout:', await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, font: getComputedStyle(document.querySelector('h1')).fontFamily })));
await page.getByRole('button', { name: 'EXPLORE GARAGE' }).click();
await page.screenshot({ path: 'artifacts/garage.png', fullPage: true });
await page.getByRole('button', { name: 'Redline home' }).click();
await page.getByRole('button', { name: 'QUICK RACE', exact: true }).click();
await page.waitForSelector('.game-canvas canvas', { timeout: 30000 });
await page.waitForTimeout(9000);
console.log('Race status:', await page.locator('.race-screen').evaluate(element => ({ phase: element.dataset.phase, speed: element.dataset.speed, text: element.innerText.slice(0, 750) })));
await page.screenshot({ path: 'artifacts/racing.png' });
await page.getByRole('button', { name: 'Pause race', exact: true }).click();
await page.screenshot({ path: 'artifacts/paused.png' });
console.log('Paused:', await page.getByRole('heading', { name: 'TAKE A BREATHER.' }).isVisible());
await page.getByRole('button', { name: 'RETURN TO RACE HUB' }).click();
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(1400);
await page.screenshot({ path: 'artifacts/mobile-hub.png', fullPage: true });
console.log('Mobile overflow:', await page.evaluate(() => document.documentElement.scrollWidth - innerWidth));
console.log('Runtime errors:', errors);
await browser.close();
if (errors.length) process.exitCode = 1;